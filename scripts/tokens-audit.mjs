#!/usr/bin/env node
// Validates tokens/*.json against schema/token-drift.schema.json and checks CSS parity.
// Writes token-audit-receipt.json. Exit 1 on any failure. `--write-css` regenerates src/styles/tokens.css.
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto'; import { execSync } from 'node:child_process'
import Ajv from 'ajv/dist/2020.js'
const root = path.resolve(import.meta.dirname, '..')
const schema = JSON.parse(fs.readFileSync(path.join(root, 'schema/token-drift.schema.json'), 'utf8'))
const sets = {}
for (const f of fs.readdirSync(path.join(root, 'tokens')).filter(f => f.endsWith('.json')).sort()) sets[f.replace('.json', '')] = JSON.parse(fs.readFileSync(path.join(root, 'tokens', f), 'utf8'))
// flatten → expected CSS vars
const expected = {}
for (const [set, { tokens }] of Object.entries(sets)) for (const [k, v] of Object.entries(tokens ?? {}))
  if (v && typeof v === 'object') for (const [sk, sv] of Object.entries(v)) expected[`--lm-${set}-${k}-${sk}`] = String(sv)
  else expected[`--lm-${set}-${k}`] = String(v)
const cssPath = path.join(root, 'src/styles/tokens.css')
if (process.argv.includes('--write-css')) {
  fs.mkdirSync(path.dirname(cssPath), { recursive: true })
  fs.writeFileSync(cssPath, `/* GENERATED by npm run tokens:sync — do not hand-edit; tokens:audit fails on drift */\n:root{\n${Object.entries(expected).map(([k, v]) => `  ${k}:${v};`).join('\n')}\n}\n`)
}
const ajv = new Ajv({ allErrors: true, strict: false }); const validate = ajv.compile(schema)
const schemaOk = validate(sets)
const schemaErrors = (validate.errors ?? []).map(e => ({ key: e.instancePath.replace(/^\//, '').replaceAll('/', '.'), message: e.message }))
const css = fs.existsSync(cssPath) ? fs.readFileSync(cssPath, 'utf8') : ''
const actual = Object.fromEntries([...css.matchAll(/(--lm-[\w-]+)\s*:\s*([^;]+);/g)].map(m => [m[1], m[2].trim()]))
const drift = []
for (const [k, v] of Object.entries(expected)) if (!(k in actual)) drift.push({ key: k, kind: 'missing-in-css', expected: v }); else if (actual[k] !== v) drift.push({ key: k, kind: 'value-mismatch', expected: v, actual: actual[k] })
for (const k of Object.keys(actual)) if (!(k in expected)) drift.push({ key: k, kind: 'orphan-css-var', actual: actual[k] })
let commit = 'unknown'; try { commit = execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim() } catch {}
const pass = schemaOk && drift.length === 0
const receipt = { pass, auditedAt: new Date().toISOString(), commit, schema: 'schema/token-drift.schema.json',
  tokensHash: crypto.createHash('sha256').update(JSON.stringify(sets)).digest('hex').slice(0, 16),
  counts: { sets: Object.keys(sets).length, tokens: Object.keys(expected).length, schemaErrors: schemaErrors.length, drifted: drift.length },
  schemaErrors, drifted: drift }
fs.writeFileSync(path.join(root, 'token-audit-receipt.json'), JSON.stringify(receipt, null, 2) + '\n')
console.log(`${pass ? 'PASS' : 'FAIL'} tokens:audit — ${receipt.counts.tokens} tokens, ${schemaErrors.length} schema errors, ${drift.length} drifted`)
for (const e of schemaErrors) console.log(`  schema  ${e.key}: ${e.message}`)
for (const d of drift) console.log(`  drift   ${d.key} (${d.kind}) expected=${d.expected ?? '-'} actual=${d.actual ?? '-'}`)
process.exit(pass ? 0 : 1)
